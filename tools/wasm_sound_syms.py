#!/usr/bin/env python3
"""Write the addresses of the sound tables the C code needs (web build).

usage: wasm_sound_syms.py <nm> <sound.elf> <out.h>
"""
import subprocess
import sys

NEEDED = ["gSongTable", "gCryTable", "gCryTable_Reverse", "voicegroup_dummy"]
BASE = 0x09000000


def main() -> None:
    nm, elf, out = sys.argv[1:4]
    symbols = {}
    for line in subprocess.run([nm, elf], check=True, capture_output=True, text=True).stdout.splitlines():
        parts = line.split()
        if len(parts) == 3:
            symbols[parts[2]] = int(parts[0], 16)

    lines = [
        "// Generated by tools/wasm_sound_syms.py from the linked sound data.",
        "#ifndef GUARD_WASM_SOUND_SYMS_H",
        "#define GUARD_WASM_SOUND_SYMS_H",
        f"#define WASM_SOUND_BASE 0x{BASE:08X}u",
    ]
    for name in NEEDED:
        if name not in symbols:
            sys.exit(f"{elf}: missing symbol {name}")
        lines.append(f"#define WASM_SOUND_{name} 0x{symbols[name]:08X}u")
    lines.append("#endif")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
